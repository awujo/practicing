"""Golden engine outputs for the speed-up regression test (tests/test_speed.py).

`python tests/engine_golden.py` rewrites tests/golden/engine_golden.json from the CURRENT engine; it was generated
from the engine before the speed-ups (commit 49d4fb7) and regenerated by the bias audit (2026-10-13: structural
swings for trend/targets, point B = last order-1 close-line turn before the first touch, sweep-of-previous-candle
story start), and again by REVIEW #26/#29/#30/#31 (STRATEGY v0.6: most recent level, flip end, higher-TF
targets, overlap / alignment / CADJPY rules), and again by the examples diagnosis (2026-10-14: `pullback_levels`,
`align_retap_ends`, `cadjpy_zone`, `tap_tol_pips` 0; engine_golden_v07.json keeps the output before it, which the
engine reproduces with PRE_EXAMPLES, tests/test_examples.py). engine_golden_v05.json keeps the v0.5 stories + taps: the engine with
the v0.6 rules switched off must still produce them (tests/test_bias_rules.py). Only regenerate after an intended
change of trading logic.
"""
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from slk.entry import find_entries  # noqa: E402
from slk.story import current_tap, find_stories  # noqa: E402
from test_engine import walk  # noqa: E402

PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "golden", "engine_golden.json")
PATH_V07 = os.path.join(os.path.dirname(os.path.abspath(__file__)), "golden", "engine_golden_v07.json")  # before the examples diagnosis, frozen
PATH_V05 = os.path.join(os.path.dirname(os.path.abspath(__file__)), "golden", "engine_golden_v05.json")  # v0.5 engine (stories + taps), frozen
CASES = [  # (pair, seed, hours, cfg)
    ("EURUSD", 1, 24 * 900, {}),
    ("EURUSD", 3, 24 * 365 * 2, {}),
    ("GBPJPY", 5, 24 * 700, {}),
    ("EURUSD", 7, 24 * 700, {"trend_filter": False, "htf_filter": False}),
    ("EURUSD", 9, 24 * 700, {"use_oc": False, "max_retaps": 0, "max_wait": 8}),
    ("EURUSD", 11, 24 * 700, {"same_bar_close": False, "tap_tol_pips": 3.0}),
]


# the four examples-diagnosis changes switched back = the v0.7 engine (tests/golden/engine_golden_v07.json)
PRE_EXAMPLES = {"pullback_levels": False, "align_retap_ends": False, "cadjpy_zone": False, "tap_tol_pips": 1.0}

LABELS = ("next_day", "retrace", "level_time")  # story labels added later (Next Day Rule etc.): no effect on outcomes


def strip_labels(x):
    """Story/tap dicts without LABELS (the golden files predate them; tests compare without them)."""
    if isinstance(x, dict):
        return {k: v for k, v in x.items() if k not in LABELS}
    if isinstance(x, list):
        return [strip_labels(v) for v in x]
    return x


def data(pair, seed, hours):
    h1 = walk(hours, seed)
    if pair.endswith("JPY"):
        h1 = h1 * 100
    return h1


def _clean(x):
    if isinstance(x, dict):
        return {k: _clean(v) for k, v in sorted(x.items())}
    if isinstance(x, (list, tuple)):
        return [_clean(v) for v in x]
    if isinstance(x, (np.floating, float)):
        return float(x)
    if isinstance(x, (np.integer,)):
        return int(x)
    if isinstance(x, (np.bool_,)):
        return bool(x)
    if isinstance(x, (pd.Timestamp, np.datetime64)):
        return str(x)
    return x


def compute():
    out = []
    for pair, seed, hours, cfg in CASES:
        h1 = data(pair, seed, hours)
        case = {"pair": pair, "seed": seed, "hours": hours, "cfg": cfg, "stories": {}, "taps": {}, "entries": {}}
        for st in ("D", "W", "M"):
            s = find_stories(pair, h1, st, cfg)
            case["stories"][st] = _clean(strip_labels(s))
            # entries pinned with the old entry model (continuation only, breakout on c4), as tests/test_speed.py checks
            old = find_entries(pair, h1, s, {"breakout_max_bars": 1, "entry_models": ["continuation"], "alignment": "off",
                                         "stop_at": "rejection", "story_end": False}, cfg, sim=True)
            case["entries"][st] = _clean([{k: v for k, v in r.items() if k not in ("model", "bo_candle", "stop_at")} for r in old])
            cuts = range(len(h1) // 2, len(h1), max(1, len(h1) // 25))
            case["taps"][st] = [_clean(strip_labels(current_tap(pair, h1.iloc[:n], st, cfg))) for n in cuts]
        out.append(case)
    return out


if __name__ == "__main__":
    json.dump(compute(), open(PATH, "w"), separators=(",", ":"), sort_keys=True)
    print("wrote", PATH, os.path.getsize(PATH))
